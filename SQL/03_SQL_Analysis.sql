-- Module 1 — Sales Fundamentals

/* Q1 — Total Revenue
   Calculate the total revenue/sales generated by NovaMart.*/
select sum(quantity*selling_price) as Total_Revenue from order_details;

/* Q2 — Total Profit
   Calculate the total profit generated by NovaMart.*/
select sum(quantity*selling_price) - sum(quantity*cost_price) as Total_profit from order_details;

/* Q3 — Overall Profit Margin
   Calculate NovaMart's overall profit margin percentage.*/
select ((sum((quantity)*(selling_price-cost_price)))/(SUM(quantity * selling_price))*100) as Profit_margin from order_details;

/* Q4 — Monthly Sales
   Calculate the total sales for every month.
   Sort chronologically from January → December.*/
select date_format(o.order_date,'%Y-%m') as Sales_Month,sum(od.Quantity*od.Selling_Price) as Revenue from orders o 
left join order_details od
on o.Order_ID = od.Order_ID
group by sales_Month
order by sales_Month asc;

/* Q5 — Monthly Profit
   Calculate the total profit for every month.
   Sort chronologically.*/
select date_format(o.order_date,'%Y-%m') as Sales_Month,
(sum(od.quantity*(od.selling_price-od.cost_price))) as Total_Profit from orders o 
left join order_details od
on o.Order_ID = od.Order_ID
group by Sales_Month
order by Sales_Month;

/* Q6 — Monthly Sales & Profit
   Create a monthly performance table containing:	Month		Total_Sales		Total_Profit*/
select date_format(o.order_date,'%Y-%m') as Sales_Month, sum(od.quantity*od.selling_price) as Total_Sales,
sum(od.quantity*(od.selling_price-od.cost_price)) as Total_profit from orders o
left join order_details od
on o.Order_ID=od.Order_ID
group by sales_month
order by sales_month;

/* Q7 — Highest Sales & Highest Profit Month
   Find:		Month with the highest sales		Month with the highest profit*/
with monthly_sales as (
select date_format(o.order_date,'%Y-%m') as Sales_Month, sum(od.quantity*od.selling_price) as Total_Sales,
sum(od.quantity*(od.selling_price-od.cost_price)) as Total_profit from orders o
left join order_details od
on o.Order_ID=od.Order_ID
group by sales_month
),
Sales_month as(
select sales_month, total_sales,total_profit,
dense_rank() over(order by total_sales desc) as Sales_Rank,
dense_rank() over(order by total_profit desc) as Profit_Rank from monthly_sales
)
select sales_month, total_sales,total_profit, 
case WHEN Sales_Rank = 1 AND Profit_Rank = 1 
	 THEN 'Highest Sales & Highest Profit'
when sales_Rank = 1
then 'Highest sales month'
when profit_rank = 1
then 'Highest Profitable Month'
end as Result from sales_month
WHERE Sales_Rank = 1 OR Profit_Rank = 1;

/* Q8 — Average Order Value
   Return:	Total_Sales		Total_Orders		Average_Order_Value*/
with AOV as(
select sum(quantity*selling_price) as Total_sales, count(distinct(Order_ID)) as Total_orders from order_details
)
select * , total_sales/total_orders as Avg_Order_Value from AOV;

