/* Q45 — Customer Segmentation 🔥🔥
   Create the following customer segments based on total revenue:		Revenue >= 50,000      → Premium
																		Revenue >= 25,000      → High Value
                                                                        Revenue >= 10,000      → Regular
                                                                        Revenue < 10,000       → Low Value*/
with Customer_Details as(
select c.Customer_id,c.Customer_name,coalesce(sum(od.quantity*od.Selling_Price),0) as Total_Revenue from customers c
left join orders o
on c.Customer_id = o.Customer_ID
left join order_details od
on o.Order_ID = od.Order_ID
group by c.Customer_id,c.Customer_name
)
select *,
case when Total_Revenue >= 50000
then 'Premium'
when Total_Revenue >= 25000
then 'High Value'
when Total_Revenue >= 10000
then 'Regular'
when Total_Revenue < 10000
then 'Low Value'
end as Revnue_Segment from customer_Details;

/* Q46 — Customer Segment Performance 🔥🔥
   Using the segmentation from Q45, calculate for each segment:*/
with Customer_Details as(
select c.Customer_id,c.Customer_name,coalesce(sum(od.quantity*od.Selling_Price),0) as Total_Revenue,
coalesce(sum(od.quantity*(od.Selling_price - od.Cost_price)),0) as Total_profit from customers c
left join orders o
on c.Customer_id = o.Customer_ID
left join order_details od
on o.Order_ID = od.Order_ID
group by c.Customer_id,c.Customer_name
),
case_seg as(
select Customer_ID,
case when Total_Revenue >= 50000
then 'Premium'
when Total_Revenue >= 25000
then 'High Value'
when Total_Revenue >= 10000
then 'Regular'
when Total_Revenue < 10000
then 'Low Value'
end as Revnue_Segment from customer_Details
)
select cs.Revnue_Segment, count(distinct cd.Customer_id) as Customer_Count, sum(cd.Total_Revenue) as Total_rev,
avg(cd.Total_Revenue) as Avg_Revenue, sum(cd.Total_profit) as Total_Profit from case_seg cs
inner join Customer_Details cd
on cs.customer_id = cd.customer_id
group by cs.Revnue_Segment
ORDER BY Total_rev DESC;




