/* 🧠 Q97 — High Revenue, Declining Products 🔥🔥🔥
   Identify products where:		They generated above-average total revenue
								Their latest month's revenue is lower than the previous month's revenue
   Expected:	Product_Name	Total_Revenue		Previous_Month_Revenue		Month_Revenue		Growth_%*/
WITH monthly AS (
    -- 1. Revenue for every product in every month
    SELECT
        DATE_FORMAT(o.Order_Date, '%Y-%m') AS Order_Month,
        p.Product_ID,
        p.Product_Name,
        SUM(od.Quantity * od.Selling_Price) AS Month_Revenue
    FROM Products p
    INNER JOIN Order_Details od
        ON p.Product_ID = od.Product_ID
    INNER JOIN Orders o
        ON od.Order_ID = o.Order_ID
    GROUP BY
        p.Product_ID,
        p.Product_Name,
        DATE_FORMAT(o.Order_Date, '%Y-%m')
),

with_previous AS (
    -- 2. Get previous month's revenue
    SELECT
        *,
        LAG(Month_Revenue) OVER (
            PARTITION BY Product_ID
            ORDER BY Order_Month
        ) AS Previous_Month_Revenue
    FROM monthly
),

latest AS (
    -- 3. Identify the latest month for each product
    SELECT
        *,
        ROW_NUMBER() OVER (
            PARTITION BY Product_ID
            ORDER BY Order_Month DESC
        ) AS Month_Rank
    FROM with_previous
),

product_total AS (
    -- 4. Calculate total revenue for each product
    SELECT
        Product_ID,
        SUM(Month_Revenue) AS Total_Revenue
    FROM monthly
    GROUP BY Product_ID
),

avg_revenue AS (
    -- 5. Calculate average product revenue
    SELECT
        AVG(Total_Revenue) AS Average_Product_Revenue
    FROM product_total
)

-- 6. Final result
SELECT
    l.Product_Name,
    pt.Total_Revenue,
    l.Previous_Month_Revenue,
    l.Month_Revenue AS Latest_Month_Revenue,
    ROUND(
        (l.Month_Revenue - l.Previous_Month_Revenue)
        / NULLIF(l.Previous_Month_Revenue, 0) * 100,
        2
    ) AS Growth_Percent
FROM latest l
INNER JOIN product_total pt
    ON l.Product_ID = pt.Product_ID
CROSS JOIN avg_revenue ar
WHERE l.Month_Rank = 1
  AND pt.Total_Revenue > ar.Average_Product_Revenue
  AND l.Month_Revenue < l.Previous_Month_Revenue;
  
/* 🧠 Q98 — Category Growth Leader 🔥🔥🔥
   For every category calculate its monthly revenue growth.
   Then identify:		The category with the highest positive month-over-month growth.
   Expected:		Month		Category_Name		Current_Revenue		Previous_Revenue		Growth_%*/
   
WITH monthly AS (
    SELECT
        DATE_FORMAT(o.Order_Date, '%Y-%m') AS Order_Month,
        c.Category_ID,
        c.Category_Name,
        SUM(od.Quantity * od.Selling_Price) AS Current_Revenue
    FROM Categories c
    INNER JOIN Products p
        ON c.Category_ID = p.Category_ID
    INNER JOIN Order_Details od
        ON p.Product_ID = od.Product_ID
    INNER JOIN Orders o
        ON od.Order_ID = o.Order_ID
    GROUP BY
        c.Category_ID,
        c.Category_Name,
        DATE_FORMAT(o.Order_Date, '%Y-%m')
),

previous_month AS (
    SELECT
        *,
        LAG(Current_Revenue) OVER (
            PARTITION BY Category_ID
            ORDER BY Order_Month
        ) AS Previous_Revenue
    FROM monthly
),

growth AS (
    SELECT
        *,
        ROUND(
            (Current_Revenue - Previous_Revenue)
            / NULLIF(Previous_Revenue, 0) * 100,
            2
        ) AS Growth_Percent
    FROM previous_month
),

ranked AS (
    SELECT
        *,
        DENSE_RANK() OVER (
            ORDER BY Growth_Percent DESC
        ) AS Growth_Rank
    FROM growth
    WHERE Growth_Percent > 0
)

SELECT
    Order_Month AS Month,
    Category_Name,
    Current_Revenue,
    Previous_Revenue,
    Growth_Percent AS Growth
FROM ranked
WHERE Growth_Rank = 1;

/* 🏆 Q99 — Customer Retention Signal 🔥🔥🔥
    Identify customers who:		placed orders in at least 2 different months
								and whose latest month's revenue is lower than their previous month's revenue
	Expected:		Customer_ID		Customer_Name		Previous_Month_Revenue		Latest_Month_Revenue		Growth_%*/
    
WITH monthly AS (
    SELECT
        c.Customer_ID,
        c.Customer_Name,
        DATE_FORMAT(o.Order_Date, '%Y-%m') AS Order_Month,
        SUM(od.Quantity * od.Selling_Price) AS Monthly_Revenue
    FROM Customers c
    INNER JOIN Orders o
        ON c.Customer_ID = o.Customer_ID
    INNER JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    GROUP BY
        c.Customer_ID,
        c.Customer_Name,
        DATE_FORMAT(o.Order_Date, '%Y-%m')
),

previous_month AS (
    SELECT
        *,
        LAG(Monthly_Revenue) OVER (
            PARTITION BY Customer_ID
            ORDER BY Order_Month
        ) AS Previous_Month_Revenue,

        ROW_NUMBER() OVER (
            PARTITION BY Customer_ID
            ORDER BY Order_Month DESC
        ) AS Month_Rank
    FROM monthly
),

customer_months AS (
    SELECT
        Customer_ID,
        COUNT(*) AS Month_Count
    FROM monthly
    GROUP BY Customer_ID
)

