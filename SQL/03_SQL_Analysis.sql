  AND cm.Month_Count >= 2
  AND pm.Monthly_Revenue < pm.Previous_Month_Revenue;

/* 👑 Q100 — Executive Business Diagnosis
   Find whether NovaMart has any months where:		Revenue -> increased MoM		BUT			Profit Margin -> decreased MoM
   Return:		Month		Revenue		Previous_Revenue		Revenue_Growth_%		Profit_Margin		Previous_Profit_Margin		
				Margin_Change
   Then answer from your SQL result:		"Which months should management investigate, and why?" */
WITH monthly AS (
    SELECT
        DATE_FORMAT(o.Order_Date, '%Y-%m') AS Order_Month,

        SUM(od.Quantity * od.Selling_Price) AS Revenue,

        SUM(
            od.Quantity *
            (od.Selling_Price - od.Cost_Price)
        ) AS Profit
    FROM Orders o
    INNER JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    GROUP BY
        DATE_FORMAT(o.Order_Date, '%Y-%m')
),

margin AS (
    SELECT
        *,
        (Profit / NULLIF(Revenue, 0)) * 100 AS Profit_Margin
    FROM monthly
),

previous_month AS (
    SELECT
        *,
        LAG(Revenue) OVER (
            ORDER BY Order_Month
        ) AS Previous_Revenue,

        LAG(Profit_Margin) OVER (
            ORDER BY Order_Month
        ) AS Previous_Profit_Margin
    FROM margin
),

final_result AS (
    SELECT
        Order_Month AS Month,
        Revenue,
        Previous_Revenue,

        ROUND(
            (Revenue - Previous_Revenue)
            / NULLIF(Previous_Revenue, 0) * 100,
            2
        ) AS Revenue_Growth,

        ROUND(Profit_Margin, 2) AS Profit_Margin,

        ROUND(Previous_Profit_Margin, 2) AS Previous_Profit_Margin,

        ROUND(
            Profit_Margin - Previous_Profit_Margin,
            2
        ) AS Margin_Change

    FROM previous_month
)

SELECT *
FROM final_result
WHERE Revenue_Growth > 0
  AND Margin_Change < 0;